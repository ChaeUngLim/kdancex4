# 학습 주석: SCH-03(환불액 산정 순수 함수 + 단위테스트) 반영
#
# 사전 개념: 이 파일은 로직이 아니라 "이미 정해졌지만 아직 쓰이지 않는 결정"을
# 상수로만 남겨 두는 파일이다. 함수가 없으니 순수 함수·StrEnum 같은 개념도 등장하지
# 않는다 — 왜 사이드 이펙트가 없는 함수 형태로 짜는지는 ``refund_policy.py``의
# 파일 상단 사전 개념 요약을 참고. 이 파일과 ``refund_policy.py``는 서로
# import하지 않는다 — 정산 결정이 회원 환불액 계산에 조용히 섞여 들어가는 것을
# 막기 위해 코드 수준에서 분리해 뒀다(아래 모듈 docstring이 그 이유를 설명한다).

from __future__ import annotations

from typing import Final

__all__ = [
    "BETA_FEE_WAIVED",
    "PG_FEE_BEARER",
    "PLATFORM_FEE_RATE_BP",
    "SETTLEMENT_REFUND_RECOVERY",
]


#: 환불 시 돌려받지 못하는 PG 건당 수수료를 누가 부담하는가 — **플랫폼 부담**.
#:
#: 산정 미반영 사유: 회원이 돌려받는 금액은 회원이 낸 금액과 학원 환불 비율표로만
#: 정해진다. PG 수수료 손실은 플랫폼이 떠안는 비용이지 회원에게 전가하는 공제가
#: 아니다. 이 값을 환불액에서 빼면 회원은 결제액의 100%를 고지받고도 그보다 적게
#: 돌려받게 되고, 이는 사전 고지한 예상 환불액과 어긋난다.
PG_FEE_BEARER: Final[str] = "platform"

#: 플랫폼이 학원에게 받는 중개 수수료율(basis point). 800bp = 8%.
#:
#: 산정 미반영 사유: 이 수수료는 **플랫폼↔학원** 정산 항목이고, 회원 환불액과는
#: 무관하다. 게다가 지금은 ``BETA_FEE_WAIVED``로 징수 자체를 하지 않는다.
#: 부동소수를 피하려고 퍼센트가 아닌 basis point 정수로 둔다
#: (``academies.refund_policy_tiers``의 ``refund_rate_bp``와 같은 단위).
PLATFORM_FEE_RATE_BP: Final[int] = 800

#: 베타 6개월간 위 8% 수수료를 면제 중인가 — **면제 중**.
#:
#: 산정 미반영 사유: 징수한 적이 없으므로 **환급할 대상 자체가 없다.** 취소 시
#: 수수료를 되돌려주는 로직을 지금 짜면 항상 0원을 돌려주는 죽은 코드가 된다.
#: 면제가 끝나면 그때 환급 규칙을 다시 정하고 정산 모듈에 넣는다.
BETA_FEE_WAIVED: Final[bool] = True

#: 이미 학원에 정산이 나간 뒤 환불이 발생하면 어떻게 회수하는가
#: — **다음 달 정산에서 차감**.
#:
#: 산정 미반영 사유: 회수는 플랫폼이 학원에게서 돈을 되받는 절차이고, 회원 환불은
#: 그와 무관하게 즉시 집행된다. 회원을 기다리게 하지 않는다는 뜻이다.
#: **이번 슬라이스 미구현** — 정산 모듈이 아직 없다. 결정을 코드에 남겨 두어
#: 정산 모듈을 만들 때 재논의 없이 이 값을 따르게 한다.
SETTLEMENT_REFUND_RECOVERY: Final[str] = "next_month_deduction"
